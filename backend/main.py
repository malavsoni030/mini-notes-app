from datetime import datetime, timezone
from pathlib import Path
import sys
from typing import List
from fastapi import Depends, FastAPI, HTTPException, Response, status
from fastapi.middleware.cors import CORSMiddleware
from sqlalchemy.orm import Session

# Ensure backend directory is in sys.path so modules import reliably
sys.path.insert(0, str(Path(__file__).resolve().parent))

try:
    from database import get_db
    from models import Note
    from schemas import NoteRequest, NoteResponse
except ImportError:
    from backend.database import get_db
    from backend.models import Note
    from backend.schemas import NoteRequest, NoteResponse

# --- Application Setup ---
app = FastAPI(title="Notes API")

# List of allowed origins for Cross-Origin Resource Sharing (CORS).
# Kept in one central list so it is easy to update or add production domains later.
ALLOWED_ORIGINS = [
    "http://localhost:5173",
    "http://127.0.0.1:5173",
]

app.add_middleware(
    CORSMiddleware,
    allow_origins=ALLOWED_ORIGINS,
    allow_credentials=True,
    allow_methods=["*"],
    allow_headers=["*"],
)


# --- API Endpoints ---

# Health check endpoint
@app.get("/")
def health_check():
    """Simple health check endpoint returning status ok."""
    return {"status": "ok"}


# Get all notes
@app.get("/api/notes", response_model=List[NoteResponse], status_code=status.HTTP_200_OK)
def get_all_notes(db: Session = Depends(get_db)):
    """Fetch all notes from the PostgreSQL database."""
    notes = db.query(Note).order_by(Note.id.asc()).all()
    return notes


# Create a new note
@app.post("/api/notes", response_model=NoteResponse, status_code=status.HTTP_201_CREATED)
def create_note(note_data: NoteRequest, db: Session = Depends(get_db)):
    """
    Create a new note in the database.
    The primary key id is generated by the database, and timestamps are set to current UTC time.
    """
    now = datetime.now(timezone.utc)
    new_note = Note(
        title=note_data.title,
        content=note_data.content,
        created_at=now,
        updated_at=now,
    )
    db.add(new_note)
    db.commit()
    db.refresh(new_note)
    return new_note


# Update an existing note
@app.put("/api/notes/{id}", response_model=NoteResponse, status_code=status.HTTP_200_OK)
def update_note(id: int, note_data: NoteRequest, db: Session = Depends(get_db)):
    """
    Update title and content of an existing note by ID.
    Refreshes updated_at to the current UTC time.
    Returns 404 if the note does not exist.
    """
    note = db.query(Note).filter(Note.id == id).first()
    if not note:
        raise HTTPException(
            status_code=status.HTTP_404_NOT_FOUND,
            detail=f"Note with id {id} not found",
        )

    note.title = note_data.title
    note.content = note_data.content
    note.updated_at = datetime.now(timezone.utc)
    db.commit()
    db.refresh(note)
    return note


# Delete a note
@app.delete("/api/notes/{id}", status_code=status.HTTP_204_NO_CONTENT)
def delete_note(id: int, db: Session = Depends(get_db)):
    """
    Delete a note from the database by its ID.
    Returns 204 No Content on success, or 404 if the note does not exist.
    """
    note = db.query(Note).filter(Note.id == id).first()
    if not note:
        raise HTTPException(
            status_code=status.HTTP_404_NOT_FOUND,
            detail=f"Note with id {id} not found",
        )

    db.delete(note)
    db.commit()
    return Response(status_code=status.HTTP_204_NO_CONTENT)
